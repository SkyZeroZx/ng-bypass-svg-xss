#!/usr/bin/env node
// Regenerates the two Angular components that hold a compiled-in data: URL.
//
// These components cannot take their URL from a query parameter -- that is the
// repository's rule, so that nothing here can be dismissed as self-XSS -- which
// means the payload has to be baked into the source. Writing it by hand went
// wrong once already: the previous literals used a relative reference
// (href="/missing-image") and reported a marker shape the matrix does not read,
// so every Angular data: row was scored as blocked for reasons that had nothing
// to do with Angular or the browser. Generating them from vectors.mjs keeps the
// compiled payload and the served payload identical by construction.
//
//   node scripts/generate-data-cases.mjs
//
// Rebuild the AOT fixtures afterwards, or the bundles keep the old literal:
//
//   npm run fixtures
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { ROOT } from './lib/pin.mjs';
import { payload } from './lib/vectors.mjs';

const svg = payload('image-onerror');
const base64 = Buffer.from(svg, 'utf8').toString('base64');

// The constructed component holds the markup in a template literal so the XSS
// reads as written. Anything a template literal would reinterpret is refused
// rather than escaped, which would make it unreadable again.
if (/[`\\]|\$\{/.test(svg)) {
  throw new Error(
    'payload contains a backtick, backslash or ${ and cannot go in a template literal',
  );
}

// The literal component carries the string an attacker would actually paste,
// wrapped so it is not one 3 KB line. It decodes to the markup shown in
// data-constructed.ts.
const chunks = base64.match(/.{1,96}/g);

const literal = [
  "import { Component } from '@angular/core';",
  '',
  '// Generated by scripts/generate-data-cases.mjs -- do not edit by hand.',
  '//',
  '// The bound value is a complete data: URL. The base64 decodes to the SVG',
  '// spelled out in data-constructed.ts.',
  '@Component({',
  "  selector: 'app-data-url',",
  "  templateUrl: './data-url.html',",
  '})',
  'export class DataUrlCase {',
  '  readonly assetUrl =',
  "    'data:image/svg+xml;base64,' +",
  ...chunks.map((chunk) => "    '" + chunk + "' +"),
  "    '#x';",
  '}',
  '',
].join('\n');

// The constructed variant keeps btoa() in the component so the compiled output
// shows the URL being assembled at runtime rather than sitting there as one
// literal string. The markup is the same payload.
const constructed = [
  "import { Component } from '@angular/core';",
  '',
  '// Generated by scripts/generate-data-cases.mjs -- do not edit by hand.',
  '//',
  '// Same payload as DataUrlCase, assembled with btoa() at runtime.',
  '//',
  '// The XSS is the onerror handler: the <image> points at bytes that are not an',
  '// image, the load fails, and the handler runs. It reports where it ran, reads',
  '// the page cookie and makes one credentialed request back to the lab origin.',
  '@Component({',
  "  selector: 'app-data-constructed',",
  "  templateUrl: './data-constructed.html',",
  '})',
  'export class DataConstructedCase {',
  '  private readonly svg = `' + svg + '`;',
  '',
  "  readonly iconUrl = 'data:image/svg+xml;base64,' + btoa(this.svg) + '#x';",
  '}',
  '',
].join('\n');

const caseDir = join(ROOT, 'src', 'app', 'cases', 'data-url');
await writeFile(join(caseDir, 'data-url.ts'), literal, 'utf8');
await writeFile(join(caseDir, 'data-constructed.ts'), constructed, 'utf8');

console.log('Wrote both data: components.');
console.log('  payload bytes : ' + svg.length);
console.log('  base64 length : ' + base64.length);
console.log(
  '  failing ref   : data:image/png;base64,Zm9v  (valid data: URL, not a decodable image)',
);
console.log('');
console.log('Then:');
console.log('  npx prettier --write src/app/cases/data-url');
console.log('');
console.log('Rebuild the AOT fixtures so the bundles pick this up:');
console.log('  npm run fixtures');
